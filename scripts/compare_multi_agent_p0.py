"""Compare multi_agent_p0 head vs baseline — 8 hard metrics, any decline → non-zero exit."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

REPORT_SCHEMA_VERSION = "p4.5-step-34-evidence-v1"
REPORT_GENERATOR = "water_agent.harness.multi_agent_eval"

THRESHOLDS: dict[str, float | int] = {
    "numeric_source_integrity": 1.0,
    "artifact_provenance_valid": 1.0,
    "unsafe_export_count": 0,
    "approval_drift_block_rate": 1.0,
    "routing_exact_match": 1.0,
    "roundtrip_segment_recall": 1.0,
    "loop_bound_violation_count": 0,
    "critical_not_checked_as_pass": 0,
}


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _metrics_of(report: dict) -> dict:
    from water_agent.harness.multi_agent_metrics import compute_multi_agent_metrics

    return compute_multi_agent_metrics(report)


def _validate_generated_report(report: dict, *, label: str) -> None:
    """Reject hand-authored metrics and reports without runtime evidence."""
    if report.get("report_schema_version") != REPORT_SCHEMA_VERSION:
        raise ValueError(f"{label} is not an evidence report from the Step 34 harness")
    if report.get("generated_by") != REPORT_GENERATOR:
        raise ValueError(f"{label} was not generated by {REPORT_GENERATOR}")
    if not isinstance(report.get("cases"), list) or not isinstance(report.get("trace_events"), list):
        raise TypeError(f"{label} is missing cases or trace_events")
    if not all(isinstance(case, dict) and "outcome" in case and "evidence" in case for case in report["cases"]):
        raise ValueError(f"{label} cases are missing runtime outcome/evidence")
    computed = _metrics_of(report)
    if report.get("metrics") != computed:
        raise ValueError(f"{label} embedded metrics do not match recomputed trace/evidence metrics")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="compare multi_agent_p0 metrics")
    p.add_argument(
        "--head",
        default="data/eval/reports/multi_agent_p0_head.json",
        help="head report json",
    )
    p.add_argument(
        "--base",
        default="data/eval/multi_agent_p0_main.json",
        help="baseline report json",
    )
    p.add_argument("--threshold", type=float, default=None, help="unused, thresholds are frozen")
    args = p.parse_args(argv)
    _ = args.threshold
    head = _load(Path(args.head))
    base = _load(Path(args.base))
    _validate_generated_report(head, label="head report")
    _validate_generated_report(base, label="baseline report")
    head_m = _metrics_of(head)
    base_m = _metrics_of(base)
    violations: list[str] = []
    rows: list[str] = []
    rows.append("| metric | base | head | threshold | status |")
    rows.append("|---|---|---|---|---|")
    for k, thr in THRESHOLDS.items():
        bv = base_m.get(k)
        hv = head_m.get(k)
        if isinstance(thr, float):
            ok = hv is not None and float(hv) >= float(thr) - 1e-9 and float(hv) >= float(bv) - 1e-9 if bv is not None else float(hv) >= float(thr) - 1e-9
            status = "OK" if ok else "FAIL"
            rows.append(f"| {k} | {bv} | {hv} | {thr} | {status} |")
            if not ok:
                violations.append(k)
        else:
            ok = hv is not None and int(hv) == int(thr) and (bv is None or int(hv) <= int(bv) or int(thr) == 0 and int(hv) == 0)
            # For defect counts, head must not exceed base and must equal threshold 0
            if int(thr) == 0:
                ok = hv is not None and int(hv) == 0
            else:
                ok = hv is not None and int(hv) == int(thr)
            status = "OK" if ok else "FAIL"
            rows.append(f"| {k} | {bv} | {hv} | {thr} | {status} |")
            if not ok:
                violations.append(k)
    md = "\n".join(rows)
    print(md)
    print(json.dumps({"ok": not violations, "violations": violations, "head_metrics": head_m, "base_metrics": base_m}, ensure_ascii=False, indent=2))
    return 1 if violations else 0


if __name__ == "__main__":
    raise SystemExit(main())
