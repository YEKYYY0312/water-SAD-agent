"""Compare memory_p0 head vs baseline — §13.2 hard metrics, any decline → non-zero exit.

The comparison refuses hand-authored reports: both sides must carry the harness
schema/generator, executed-case counters for every case, and embedded metrics
that recompute from those counters.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

REPORT_SCHEMA_VERSION = "p5-step-45-memory-evidence-v1"
REPORT_GENERATOR = "water_agent.harness.memory_eval"
MIN_SUITE_CASES = 36


def _load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _metrics_of(report: dict[str, Any]) -> dict[str, Any]:
    from water_agent.harness.memory_metrics import compute_memory_metrics

    return compute_memory_metrics(report)


def _is_runtime_skip(case: dict[str, Any]) -> bool:
    from water_agent.harness.memory_metrics import is_runtime_skip_case

    return is_runtime_skip_case(case)


def _validate_generated_report(report: dict[str, Any], *, label: str) -> None:
    """Reject hand-authored metrics and reports without executed-case counters."""

    if report.get("report_schema_version") != REPORT_SCHEMA_VERSION:
        raise ValueError(f"{label} is not an evidence report from the Step 45 harness")
    if report.get("generated_by") != REPORT_GENERATOR:
        raise ValueError(f"{label} was not generated by {REPORT_GENERATOR}")
    cases = report.get("cases")
    if not isinstance(cases, list) or not cases:
        raise TypeError(f"{label} is missing executed cases")
    if len(cases) < MIN_SUITE_CASES:
        raise ValueError(f"{label} has {len(cases)} cases; the suite requires >= {MIN_SUITE_CASES}")
    for case in cases:
        if not isinstance(case, dict) or "outcome" not in case:
            raise ValueError(f"{label} cases are missing a runtime outcome")
        if _is_runtime_skip(case):
            if not case.get("skip_reason"):
                raise ValueError(f"{label} case {case.get('case_id')} skipped without a reason")
            continue
        counters = case.get("counters")
        if not isinstance(counters, dict) or not counters:
            raise ValueError(f"{label} case {case.get('case_id')} has no metric counters")
        if "evidence" not in case:
            raise ValueError(f"{label} case {case.get('case_id')} has no runtime evidence")
    computed = _metrics_of(report)
    if report.get("metrics") != computed:
        raise ValueError(f"{label} embedded metrics do not match recomputed case counters")
    missing = computed.get("missing_required_counters") or []
    if missing:
        raise ValueError(f"{label} has unmeasured counters: {missing[:5]}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="compare memory_p0 hard metrics")
    parser.add_argument(
        "--head", default="data/eval/reports/memory_p0_head.json", help="head report json"
    )
    parser.add_argument(
        "--base", default="data/eval/memory_p0_main.json", help="baseline report json"
    )
    args = parser.parse_args(argv)
    from water_agent.harness.memory_metrics import HARD_THRESHOLDS, RATE_METRICS

    head = _load(Path(args.head))
    base = _load(Path(args.base))
    try:
        _validate_generated_report(head, label="head report")
        _validate_generated_report(base, label="baseline report")
    except (TypeError, ValueError) as exc:
        print(
            json.dumps(
                {"ok": False, "reason": "invalid_report", "error": str(exc)},
                ensure_ascii=False,
            )
        )
        return 2
    head_metrics = _metrics_of(head)
    base_metrics = _metrics_of(base)

    violations: list[str] = []
    rows = ["| metric | base | head | threshold | status |", "|---|---|---|---|---|"]
    for name, threshold in HARD_THRESHOLDS.items():
        base_value = base_metrics.get(name)
        head_value = head_metrics.get(name)
        if name in RATE_METRICS:
            # A rate must meet its floor and must not regress against the baseline.
            ok = head_value is not None and float(head_value) >= float(threshold) - 1e-9
            if ok and base_value is not None:
                ok = float(head_value) >= float(base_value) - 1e-9
        else:
            # A defect count must be exactly at its ceiling (0) and not grow.
            ok = head_value is not None and int(head_value) <= int(threshold)
            if ok and base_value is not None:
                ok = int(head_value) <= int(base_value)
        rows.append(
            f"| {name} | {base_value} | {head_value} | {threshold} | {'OK' if ok else 'FAIL'} |"
        )
        if not ok:
            violations.append(name)

    head_cases = {case["case_id"]: case for case in head["cases"]}
    base_passed = {case["case_id"] for case in base["cases"] if case.get("outcome") == "pass"}

    # A case that head SKIPPED is out of scope for the regression comparison, but
    # only when it declares an environmental prerequisite.  An undeclared SKIP is
    # a violation in its own right: no case in this suite may quietly opt out.
    undeclared_skips = sorted(
        case_id
        for case_id, case in head_cases.items()
        if _is_runtime_skip(case) and not case.get("requires")
    )
    if undeclared_skips:
        violations.extend(f"undeclared_skip:{case_id}" for case_id in undeclared_skips)

    evaluated_head = {
        case_id
        for case_id, case in head_cases.items()
        if not _is_runtime_skip(case) and case.get("outcome") == "pass"
    }
    regressed = sorted(base_passed - evaluated_head)
    if regressed:
        violations.extend(f"case_regression:{case_id}" for case_id in regressed)
    emitted = sorted(head_cases)
    if emitted != sorted(case["case_id"] for case in base["cases"]):
        violations.append("suite_case_set_changed")

    print("\n".join(rows))
    print(
        json.dumps(
            {
                "ok": not violations,
                "violations": violations,
                "regressed_cases": regressed,
                "head_metrics": head_metrics,
                "base_metrics": base_metrics,
            },
            ensure_ascii=False,
            indent=2,
        )
    )
    return 1 if violations else 0


if __name__ == "__main__":
    raise SystemExit(main())
